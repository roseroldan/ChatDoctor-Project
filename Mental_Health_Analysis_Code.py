"""## Data cleaning

### Subtask:
Clean the 'cleaned_text' column of the DataFrame.

**Reasoning**:
Clean the 'cleaned_text' column by handling missing values, removing irrelevant characters, applying lemmatization, and converting text to lowercase.  Create a new column 'cleaned_text_processed' to store the results.
"""

import re
import nltk
from nltk.stem import WordNetLemmatizer
nltk.download('wordnet')
nltk.download('omw-1.4')

# 1. Handle missing values
df['cleaned_text'].fillna('', inplace=True)

# Initialize the lemmatizer
lemmatizer = WordNetLemmatizer()

def clean_text(text):
    # 2. Remove irrelevant characters
    text = re.sub(r'[^\w\s]', '', text)  # Remove punctuation
    text = re.sub(r'\d+', '', text)  # Remove numbers
    text = re.sub(r'http\S+', '', text) # Remove URLs

    # 3. Lemmatize
    words = text.split()
    lemmatized_words = [lemmatizer.lemmatize(word) for word in words]
    text = " ".join(lemmatized_words)

    # 4. Convert to lowercase (optional, but recommended)
    text = text.lower()
    return text

# Apply the cleaning function to the 'cleaned_text' column
df['cleaned_text_processed'] = df['cleaned_text'].apply(clean_text)

